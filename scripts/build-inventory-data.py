#!/usr/bin/env python3
"""Regenerates src/features/inventory/constants/{species,plots,trees}.ts from the research workbook.

Usage: python3 scripts/build-inventory-data.py ~/Documents/SE-Data/Tagging_Tanaman_AGB_BGB_2026.xlsx
Standard library only. Reads the sheets Dashboard (plot order), Metode & Parameter (species table),
Data Pohon (trees). AGB/BGB/carbon are NOT copied: the app recomputes them from DBH and rho.
"""
import json, re, sys, zipfile
import xml.etree.ElementTree as ET

M = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"
R = "{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id"
OUT = "src/features/inventory/constants/"
ROMAN = ["I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX", "X", "XI", "XII", "XIII"]
# workbook location -> map zone names (zona_vak.csv). Anything not listed has no map zone.
ZONES = {f"VAK {n}": [f"Vak {ROMAN[n - 1]}"] for n in range(1, 13)}
ZONES["VAK 9 & 10"] = ["Vak IX", "Vak X"]
ZONES["VAK 10 Lorong Casuarina"] = []
ZONES["Zona 5 MA = VAK 13"] = ["Vak XIII"]  # stated in the sheet name itself


def read(path):
    z = zipfile.ZipFile(path)
    strings = ["".join(t.text or "" for t in si.iter(M + "t")) for si in ET.fromstring(z.read("xl/sharedStrings.xml")).findall(M + "si")]
    rels = {r.get("Id"): r.get("Target") for r in ET.fromstring(z.read("xl/_rels/workbook.xml.rels"))}
    sheets = {}
    for s in ET.fromstring(z.read("xl/workbook.xml")).find(M + "sheets"):
        target = rels[s.get(R)].lstrip("/")
        rows = []
        for row in ET.fromstring(z.read(target if target.startswith("xl/") else "xl/" + target)).iter(M + "row"):
            cells = {}
            for c in row.findall(M + "c"):
                v = c.find(M + "v")
                if v is not None:
                    cells[re.match(r"[A-Z]+", c.get("r")).group()] = strings[int(v.text)] if c.get("t") == "s" else v.text
            rows.append((int(row.get("r")), cells))
        sheets[s.get("name")] = rows
    return sheets


def ts(name, doc, typ, value):
    const = name.split(".")[0].upper()
    with open(OUT + name, "w") as f:
        f.write(f'import type {{ {typ.split("[")[0]} }} from "../types/inventory";\n\n// {doc}\nexport const {const}: {typ} = {json.dumps(value, ensure_ascii=False)};\n')


wb = read(sys.argv[1])
plots = [d["B"] for r, d in wb["Dashboard"] if 12 <= r <= 30]
species = [[d["B"], d["C"], d["D"], float(d["E"]), d["F"]] for r, d in wb["Metode & Parameter"] if 44 <= r <= 80]
sp_index = {s[0]: i for i, s in enumerate(species)}
trees = []
for r, d in wb["Data Pohon"][1:]:
    qc = {"OK": 0, "Sudah diperbaiki": 1, "Perlu verifikasi": 2}[d["T"]]
    row = [plots.index(d["B"]), int(d["C"]), sp_index[d["E"]], float(d["J"]), qc]
    if qc and d.get("U"):
        row.append(d["U"])
    trees.append(row)

SRC = "Generated by scripts/build-inventory-data.py from SE-Data/Tagging_Tanaman_AGB_BGB_2026.xlsx; do not edit by hand. shortcut: static copy of research data (Q-03/Q-08), replace with a query layer."
ts("species.ts", SRC + " Row: [name, family, group, rho g/cm3, rho basis].", "SpeciesRow[]", species)
ts("plots.ts", SRC + " Row: [label, map zones].", "PlotRow[]", [[p, ZONES.get(p, [])] for p in plots])
ts("trees.ts", SRC + " Row: [plot index, tag, species index, DBH cm, QC 0 ok/1 fixed/2 verify, QC note].", "TreeRow[]", trees)
print(len(plots), len(species), len(trees))
